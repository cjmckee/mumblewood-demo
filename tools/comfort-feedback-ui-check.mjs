import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
try {
 for (const width of [1440, 390, 320]) {
  const context = await browser.newContext({ viewport: { width, height: 900 }, offline: true });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setContent(readFileSync('dist/comfort-feedback/index.html', 'utf8'));
  assert.equal(await page.locator('#hud-level').innerText(), 'Comfort II');
  assert.match(await page.locator('#charter-note').innerText(), /II → I/);
  await page.screenshot({ path: `dist/comfort-feedback/${width}-hud.png`, fullPage: true });
  await page.locator('#open-comfort').focus(); await page.keyboard.press('Enter');
  assert.equal(await page.locator('dialog').evaluate(d => d.open), true);
  assert.equal(await page.locator('[role=tabpanel]:visible .track-row.qualifies').count(), 2);
  assert.match(await page.locator('.next-step').innerText(), /Evenings: 5 points below/);
  assert.match(await page.locator('.next-step').innerText(), /Level III adds 5% chance/);
  await page.screenshot({ path: `dist/comfort-feedback/${width}-now.png`, fullPage: true });
  await page.locator('#tab-next').focus(); await page.keyboard.press('Enter');
  assert.match(await page.locator('#comfort-body').innerText(), /Level II → I/);
  assert.match(await page.locator('#comfort-body').innerText(), /lose: 5% faster workshop work/);
  assert.equal(await page.locator('[role=tabpanel]:visible .track-row.qualifies').count(), 1);
  assert.match(await page.locator('[role=tabpanel]:visible .track-row').first().innerText(), /Would become inactive/);
  await page.screenshot({ path: `dist/comfort-feedback/${width}-next.png`, fullPage: true });
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#tab-now').getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').evaluate(d => d.open), false);
  assert.equal(await page.locator('#open-comfort').evaluate(e => e === document.activeElement), true);
  await page.locator('#example-scenario').selectOption('thriving');
  assert.equal(await page.locator('#hud-level').innerText(), 'Comfort III');
  assert.match(await page.locator('#charter-note').innerText(), /stays III/);
  await page.locator('#open-next').click();
  assert.match(await page.locator('#comfort-body').innerText(), /rewards would remain active/);
  await page.locator('#close-dialog').click();
  await page.locator('#example-scenario').selectOption('warming');
  assert.match(await page.locator('#hud-count').innerText(), /8\/24h/);
  await page.locator('#open-comfort').click();
  assert.equal(await page.locator('[role=tabpanel]:visible .track-row.qualifies').count(), 0);
  assert.match(await page.locator('#comfort-body').innerText(), /16 more hours/);
  await page.locator('#tab-next').click();
  assert.match(await page.locator('#comfort-body').innerText(), /not yet a full day/);
  await page.keyboard.press('Escape');
  await page.locator('#example-scenario').selectOption('village');
  assert.equal(await page.locator('#open-next').isVisible(), false);
  await page.locator('#open-comfort').click();
  assert.equal(await page.locator('#tab-next').isVisible(), false);
  await page.keyboard.press('Escape');
  await page.locator('#example-scenario').selectOption('preparing');
  await page.locator('.examples summary').click();
  await page.locator('#example-evenings').fill('50');
  assert.equal(await page.locator('#hud-level').innerText(), 'Comfort III', 'exact threshold equality activates a track');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page fits viewport');
  assert.deepEqual(errors, []);
  await context.close();
  console.log(`${width}px: HUD, now/next tracks, lost rewards, warmup, final charter, threshold equality, keyboard and focus passed`);
 }
} finally { await browser.close(); }
