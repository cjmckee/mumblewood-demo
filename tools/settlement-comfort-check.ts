import assert from 'node:assert/strict';
import { createWorld, runHours } from '../src/sim/world';
import { preparePlayerSettlement } from '../src/settlement';
const w = createWorld(42), rng = w.rngState;
preparePlayerSettlement(w);
assert.equal(w.comfortMilestones!.profile, 'balanced');
assert.equal(w.rngState, rng, 'enabling rewards does not consume event RNG');
assert.equal(w.comfortMilestones!.history.length, 0, 'legacy saves get no invented history');
runHours(w, 3);
const restored = JSON.parse(JSON.stringify(w));
preparePlayerSettlement(restored);
assert.equal(JSON.stringify(restored), JSON.stringify(w), 'resume preserves the saved world, history and bonus stream');
const oldWin = createWorld(43); oldWin.status = 'won';
const before = JSON.stringify(oldWin); preparePlayerSettlement(oldWin);
assert.equal(JSON.stringify(oldWin), before, 'completed results are not changed retroactively');
const next = preparePlayerSettlement(createWorld(44));
assert.equal(next.comfortMilestones!.profile, 'balanced');
assert.equal(next.comfortMilestones!.history.length, 0);
console.log('player comfort: enabled defaults, legacy warmup, exact resume and completed-result preservation passed');
